/**
 * Test controller for OrdersCheckoutApiController.
 */
class OrdersCheckoutApiControllerTest {

    private val log: Logger = LoggerFactory.getLogger(javaClass)

    private val context = ServicesInMemoryConfig()

    private val controller = OrdersCheckoutApiController( context.ordersCheckoutService() )

    @BeforeEach
    fun setUp() {
        context.reloadTestData()
    }


    @Test
    fun startOrderCheckoutTest() {
        // Java DTOs generated by openapi-generator: use fluent setters, not Kotlin named arguments.
        // G-FT-03: `items` must have at least one line (OpenAPI minlength(1)) and the sku must be one
        // InventoryService actually has stock for (AE-PRT-002, fixture InventoryPosition#2), otherwise
        // startOrderCheckout now correctly throws StockUnavailableException instead of returning 201.
        val itemDTO: OrderItemInputDTO = OrderItemInputDTO()
            .sku("AE-PRT-002")
            .quantity(1)
            .unitPrice(BigDecimal("25.00"))
        val reqBody: StartOrderCheckoutInputDTO = StartOrderCheckoutInputDTO()
            .customerId("CUST-999")
            .customerEmail("new@example.com")
            .paymentMethodId("pm_card_visa")
            .currency("EUR")
            .items(mutableListOf(itemDTO))
            .shippingAddress(
                ShippingAddressInputDTO()
                    .name("Ada Lovelace")
                    .line1("12 Marylebone Rd")
                    .city("London")
                    .postalCode("NW1 5LR")
                    .country("GB")
            )
        val response = controller.startOrderCheckout(reqBody)
        Assertions.assertEquals(201, response.statusCode.value())
    }


}
